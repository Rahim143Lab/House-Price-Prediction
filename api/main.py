"""
FastAPI backend for the House Price Prediction system.

Run with:
    uvicorn api.main:app --reload
"""

from __future__ import annotations

import logging

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, ConfigDict, Field, field_validator

from src import config
from src.predict import (
    HouseFeatures,
    InvalidInputError,
    ModelNotLoadedError,
    get_model_info,
    predict_house_price,
)
from src.utils import setup_logging

setup_logging()
logger = logging.getLogger(__name__)

app = FastAPI(
    title=config.API_TITLE,
    description=config.API_DESCRIPTION,
    version=config.API_VERSION,
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=config.ALLOWED_ORIGINS,
    allow_credentials=False,
    allow_methods=["GET", "POST"],
    allow_headers=["*"],
)


# ---------------------------------------------------------------------------
# Request / response schemas
# ---------------------------------------------------------------------------
class PredictionRequest(BaseModel):
    bedrooms: int = Field(..., ge=0, le=12, description="Number of bedrooms above grade")
    bathrooms: float = Field(..., ge=0, le=8, description="Total bathrooms (half baths count as .5)")
    living_area: float = Field(..., gt=0, description="Above-grade living area in square feet")
    lot_area: float = Field(..., gt=0, description="Lot size in square feet")
    floors: float = Field(..., ge=1, le=3, description="Approximate number of floors")
    garage_cars: int = Field(..., ge=0, le=5, description="Garage capacity in cars")
    year_built: int = Field(..., ge=1870, le=2026, description="Year the property was built")
    year_remodeled: int | None = Field(
        None, ge=1870, le=2026, description="Year of last remodel/addition (optional)"
    )
    neighborhood: str = Field(..., description="Neighborhood / location code")
    bldg_type: str = Field(..., description="Building type, e.g. 1Fam, TwnhsE, Duplex")
    overall_qual: int = Field(..., ge=1, le=10, description="Overall material/finish quality (1-10)")
    overall_cond: int = Field(..., ge=1, le=10, description="Overall property condition (1-10)")
    total_rooms: int = Field(..., ge=1, le=20, description="Total rooms above grade")
    fireplaces: int = Field(0, ge=0, le=5)
    central_air: str = Field("Y", description="'Y' or 'N'")
    has_deck_or_porch: bool = Field(False)

    @field_validator("central_air")
    @classmethod
    def _validate_central_air(cls, v: str) -> str:
        v = v.upper()
        if v not in ("Y", "N"):
            raise ValueError("central_air must be 'Y' or 'N'")
        return v

    model_config = ConfigDict(
        json_schema_extra={
            "example": {
                "bedrooms": 3,
                "bathrooms": 2.5,
                "living_area": 1800,
                "lot_area": 8000,
                "floors": 2,
                "garage_cars": 2,
                "year_built": 2005,
                "year_remodeled": 2010,
                "neighborhood": "NAmes",
                "bldg_type": "1Fam",
                "overall_qual": 7,
                "overall_cond": 6,
                "total_rooms": 7,
                "fireplaces": 1,
                "central_air": "Y",
                "has_deck_or_porch": True,
            }
        }
    )


class EstimatedRange(BaseModel):
    low: float
    high: float
    basis: str


class PredictionResponse(BaseModel):
    predicted_price: float
    currency: str
    model: str
    estimated_range: EstimatedRange | None = None
    disclaimer: str = (
        "This is an estimate produced by a machine learning model trained on "
        "historical sales data. It is not a guaranteed market price or an "
        "appraisal; actual prices depend on many real-world factors."
    )


# ---------------------------------------------------------------------------
# Endpoints
# ---------------------------------------------------------------------------
@app.get("/")
def root():
    """Basic API information."""
    return {
        "name": config.API_TITLE,
        "version": config.API_VERSION,
        "description": config.API_DESCRIPTION,
        "endpoints": ["/", "/health", "/model-info", "/predict", "/docs"],
    }


@app.get("/health")
def health():
    return {"status": "healthy"}


@app.get("/model-info")
def model_info():
    try:
        return get_model_info()
    except Exception as exc:  # pragma: no cover - defensive
        logger.exception("Failed to load model info")
        raise HTTPException(status_code=500, detail="Unable to load model information.") from exc


@app.get("/feature-importance")
def feature_importance():
    """Return the model's feature importance table, generated by
    `python -m src.evaluate`, for the frontend's 'About Model' page."""
    import pandas as pd

    path = config.METRICS_DIR / "feature_importance.csv"
    if not path.exists():
        raise HTTPException(
            status_code=404,
            detail="Feature importance not yet generated. Run `python -m src.evaluate`.",
        )
    df = pd.read_csv(path)
    return df.head(10).to_dict(orient="records")


@app.post("/predict", response_model=PredictionResponse)
def predict(request: PredictionRequest):
    logger.info("Received prediction request for neighborhood=%s", request.neighborhood)
    features = HouseFeatures(
        bedrooms=request.bedrooms,
        bathrooms=request.bathrooms,
        living_area=request.living_area,
        lot_area=request.lot_area,
        floors=request.floors,
        garage_cars=request.garage_cars,
        year_built=request.year_built,
        year_remodeled=request.year_remodeled,
        neighborhood=request.neighborhood,
        bldg_type=request.bldg_type,
        overall_qual=request.overall_qual,
        overall_cond=request.overall_cond,
        total_rooms=request.total_rooms,
        fireplaces=request.fireplaces,
        central_air=request.central_air,
        has_deck_or_porch=request.has_deck_or_porch,
    )
    try:
        result = predict_house_price(features)
    except InvalidInputError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc
    except ModelNotLoadedError as exc:
        logger.error("Model not available: %s", exc)
        raise HTTPException(
            status_code=503, detail="Prediction model is not available. Please try again later."
        ) from exc
    except Exception as exc:  # pragma: no cover - defensive
        logger.exception("Unexpected error during prediction")
        raise HTTPException(status_code=500, detail="An unexpected error occurred.") from exc

    logger.info("Prediction successful: %s", result["predicted_price"])
    return result
